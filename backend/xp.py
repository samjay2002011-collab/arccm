"""جدول الخبرة الرسمي (مستخرج حرفياً من حزمة rampart: مصفوفة عتبات الـ XP).

المستوي = آخر عتبة <= XP الحالي، والحد الأقصى 75 (نفس ما يعرضه الموقع في الحلقة الصفراء).
"""

XP_TABLE = [0, 5000, 15000, 26000, 37000, 49000, 62000, 76000, 91000, 107000, 124000, 142000,
            161000, 181000, 202000, 224000, 248000, 273000, 299000, 326000, 354000, 383000,
            414000, 446000, 479000, 513000, 548000, 584000, 621000, 659000, 697000, 736000,
            776000, 817000, 858000, 900000, 943000, 986000, 1030000, 1074000, 1119000, 1164000,
            1210000, 1256000, 1302000, 1349000, 1396000, 1443000, 1490000, 1538000, 1586000,
            1634000, 1682000, 1730000, 1778000, 1827000, 1876000, 1925000, 1974000, 2023000,
            2072000, 2121000, 2170000, 2219000, 2268000, 2317000, 2366000, 2416000, 2466000,
            2516000, 2566000, 2616000, 2666000, 2716000, 2766000, 2816000]

MAX_LEVEL = len(XP_TABLE) - 1


def level_from_xp(xp):
    """(level, xp_floor, xp_next, progress%) — نفس حساب الحلقة الصفراء في الهيدر."""
    xp = int(xp or 0)
    idx = MAX_LEVEL
    for i in range(MAX_LEVEL, -1, -1):
        if xp >= XP_TABLE[i]:
            idx = i
            break
    floor = XP_TABLE[idx]
    nxt = XP_TABLE[idx + 1] if idx + 1 <= MAX_LEVEL else floor
    if idx == MAX_LEVEL or nxt == floor:
        progress = 100.0
    else:
        progress = (xp - floor) / float(nxt - floor) * 100.0
    return {"level": idx, "xp": xp, "floor": floor, "next": nxt, "progress": round(progress, 2),
            "max_level": idx == MAX_LEVEL}
